(function() {
  function getLanguage() {
    return localStorage.getItem('newgen_lang') || 'es';
  }

  function applyLanguage(lang) {
    if (!landingTranslations[lang]) lang = 'es';
    localStorage.setItem('newgen_lang', lang);
    document.documentElement.lang = lang;

    const dict = landingTranslations[lang];

    // Actualizar elementos con data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // Actualizar botón de idioma
    const langBtn = document.getElementById('langToggle');
    if (langBtn) {
      langBtn.textContent = dict.lang_btn;
      langBtn.title = lang === 'es' ? 'Cambiar a Inglés' : 'Switch to Spanish';
    }
  }

  function toggleLanguage() {
    const current = getLanguage();
    const next = current === 'es' ? 'en' : 'es';
    applyLanguage(next);
  }

  function init() {
    applyLanguage(getLanguage());
    const langBtn = document.getElementById('langToggle');
    if (langBtn) {
      langBtn.onclick = function(e) {
        e.preventDefault();
        toggleLanguage();
      };
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }

  window.NewGenLang = {
    get: getLanguage,
    set: applyLanguage,
    toggle: toggleLanguage
  };
})();
